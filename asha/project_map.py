"""Project orientation: deterministic facts + provenance, zero-daemon.

A thin SYNTHESIS layer over existing capabilities (git, config files,
filesystem, lightweight AST patterns). It is not an AST engine, not a
search engine, not a scope resolver, not an evidence engine.

Output schema (stable, schema=1):

    {schema, cache_key, repo, stack, layout, tooling,
     entry_points, hotspots, generated_candidates, warnings}

Every detected fact carries provenance:
    {"value": ..., "source": ..., "confidence": ...}
confidence is one of: direct | detected | inferred  (never fabricated;
fact() rejects anything else).

Modes:
    --quick      git state, stack, layout, tooling, config locations
    --standard   + entry points, hotspots, generated candidates, warnings
    --deep       + schema/model candidates and public symbol inventory

Cache: external state cache/orient.json keyed per mode by tree_hash (clean tree
only). A dirty working tree bypasses the persistent cache entirely --
stale orientation is never served.
"""

from __future__ import annotations

